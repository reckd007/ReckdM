const seenToolIds = new Set<string>();
export const allTools: ToolItem[] = ALL_TOOLS.filter((t) => {
  if (seenToolIds.has(t.id)) return false;
  seenToolIds.add(t.id);
  return true;
}).map((t) => {
  const rawTags = [
    t.categoryId,
    ...t.id.split('-'),
    ...(t.badge ? [t.badge.toLowerCase()] : []),
  ];
  const uniqueTags = Array.from(
    new Set(
      rawTags
        .map((tag) => tag.trim().toLowerCase())
        .filter((tag) => tag.length > 0)
    )
  );

  return {
    ...t,
    name: t.title,
    category: t.categoryId,
    emoji: CATEGORY_EMOJIS[t.categoryId] || '⚡',
    tags: uniqueTags,
  };
});

export const toolCategories: ToolCategory[] = CATEGORIES.map((c) => {
  const tools = allTools.filter((t) => t.category === c.id);
  return {
    ...c,
    name: c.title,
    emoji: c.emoji || CATEGORY_EMOJIS[c.id] || '⚡',
    count: tools.length,
    tools,
  };
});

